#!/usr/bin/env python3
"""Build surfaces/art/t3-rift.svg: the T3 schematic Rift (recipe card T3).

The T1 geometry as flat shapes on a 100x100 unit square, never traced:
canvas ground framed by a 1 px rule square, four jungle quadrants, the river
as an 8-unit band, lanes as 4-unit bands, bases as filled side shapes
(circle blue, square red). Straight polygon edges, sharp corners, one fill
per element, no outlines on shapes. Fills come from art/t3.css (tokens only).
Run from the repo root:  python3 -I .planning/missions/M151/gallery/tools/build-t3-rift.py
"""
import math, pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "surfaces" / "art" / "t3-rift.svg"
f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
R2 = math.sqrt(2)

FRAME = (2.0, 98.0)             # canvas square, rule hairline
LANE_C = (10.0, 90.0)           # lane centre lines (top/left at 10, bot/right at 90)
LANE_W = 4.0
RIVER_W = 8.0
GAP = 1.5                       # canvas verge between jungle and every lane, river, base
BLUE = (10.0, 90.0, 5.0)        # base circle: centre, r
RED = (90.0, 10.0, 9.0)         # base square: centre, side

def clip(poly, a, b, c):
    """Sutherland-Hodgman: keep a*x + b*y + c >= 0."""
    out = []
    n = len(poly)
    for i in range(n):
        p, q = poly[i], poly[(i + 1) % n]
        fp, fq = a * p[0] + b * p[1] + c, a * q[0] + b * q[1] + c
        if fp >= 0: out.append(p)
        if (fp >= 0) != (fq >= 0):
            t = fp / (fp - fq)
            out.append((p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t))
    return out

def poly_d(pts):
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts) + " Z"

lo, hi = LANE_C[0] - LANE_W / 2, LANE_C[1] + LANE_W / 2      # 8, 92: lane outer edges
ilo, ihi = LANE_C[0] + LANE_W / 2, LANE_C[1] - LANE_W / 2    # 12, 88: lane inner edges
square = [(lo, lo), (hi, lo), (hi, hi), (lo, hi)]

# Lanes: two L-shaped bands with mitred elbows, and the mid diagonal.
top = [(lo, BLUE[1]), (lo, lo), (RED[0], lo), (RED[0], ilo), (ilo, ilo), (ilo, BLUE[1])]
bot = [(BLUE[0], ihi), (ihi, ihi), (ihi, RED[1]), (hi, RED[1]), (hi, hi), (BLUE[0], hi)]
h = LANE_W / 2 / R2
mid = [(BLUE[0] - h, BLUE[1] - h), (RED[0] - h, RED[1] - h), (RED[0] + h, RED[1] + h), (BLUE[0] + h, BLUE[1] + h)]

# River: an 8-unit band on y = x, ends cut square to the lane box.
w = RIVER_W / 2 / R2
river = [(0 + w, 0 - w), (100 + w, 100 - w), (100 - w, 100 + w), (0 - w, 0 + w)]
for hp in ((1, 0, -lo), (-1, 0, hi), (0, 1, -lo), (0, -1, hi)):
    river = clip(river, *hp)

# Jungle quadrants: the space between lane, river and mid, inset by GAP.
r = 1 / R2
rv = RIVER_W / 2 + GAP          # from the river centre line
md = LANE_W / 2 + GAP           # from the mid centre line
base_b = BLUE[2] + GAP + 1.0    # along the mid axis, clear of the bases
base_r = RED[2] / 2 * R2 + GAP + 0.5
QUADS = {
    "left":   [(1, 0, -(ilo + GAP)), (-r, r, -rv), (-r, -r, 100 * r - md)],
    "top":    [(0, 1, -(ilo + GAP)), (r, -r, -rv), (-r, -r, 100 * r - md)],
    "right":  [(-1, 0, ihi - GAP), (r, -r, -rv), (r, r, -100 * r - md)],
    "bottom": [(0, -1, ihi - GAP), (-r, r, -rv), (r, r, -100 * r - md)],
}
# Base clearances: distance along the mid axis from each base centre.
# Blue (10,90): ((x-10) - (y-90)) / sqrt2 >= base_b ; red (90,10): ((90-x) + (y-10)) / sqrt2 >= base_r
BASE_HP = [(r, -r, (-BLUE[0] + BLUE[1]) * r - base_b), (-r, r, (RED[0] - RED[1]) * r - base_r)]
jungle = []
for name, hps in QUADS.items():
    p = list(square)
    for hp in hps + BASE_HP:
        p = clip(p, *hp)
    jungle.append(poly_d(p))

bx, by, br = BLUE
rx, ry, rs = RED
blue = f"M{f(bx - br)},{f(by)} a{f(br)},{f(br)} 0 1 0 {f(2 * br)},0 a{f(br)},{f(br)} 0 1 0 {f(-2 * br)},0 Z"
red = poly_d([(rx - rs / 2, ry - rs / 2), (rx + rs / 2, ry - rs / 2), (rx + rs / 2, ry + rs / 2), (rx - rs / 2, ry + rs / 2)])

# Edge ticks (1280 only, muted): 8 columns along the top, 5 rows down the left.
ticks = [f"M{f(2 + 96 * i / 8)},2 V0.4" for i in range(1, 8)] + [f"M2,{f(2 + 96 * i / 5)} H0.4" for i in range(1, 5)]

# Chalk leader: from the blue base edge to the "YOUR TEAM" label (t3.json label).
ang = math.atan2(84.2 - by, 22.3 - bx)
sx, sy = bx + (br + 0.8) * math.cos(ang), by + (br + 0.8) * math.sin(ang)
leader = f"M{f(sx)},{f(sy)} L22.3,84.2"

F0, F1 = FRAME
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" class="rift rift-t3" aria-hidden="true" focusable="false">
<!-- GENERATED by tools/build-t3-rift.py (recipe card T3). Do not edit by hand. -->
<g class="ticks">{"".join(f'<path d="{d}"/>' for d in ticks)}</g>
<rect class="t3-ground" x="{f(F0)}" y="{f(F0)}" width="{f(F1 - F0)}" height="{f(F1 - F0)}"/>
<g class="t3-jungle">{"".join(f'<path d="{d}"/>' for d in jungle)}</g>
<path class="t3-river" d="{poly_d(river)}"/>
<g class="t3-lane"><path d="{poly_d(top)}"/><path d="{poly_d(bot)}"/><path d="{poly_d(mid)}"/></g>
<path class="t3-base t3-base-blue" d="{blue}"/>
<path class="t3-base t3-base-red" d="{red}"/>
<g class="chalk" data-for="team-label"><path d="{leader}"/></g>
</svg>
'''
OUT.write_text(svg)
print(f"{OUT} {len(jungle)} jungle quadrants, {len(svg)} bytes")

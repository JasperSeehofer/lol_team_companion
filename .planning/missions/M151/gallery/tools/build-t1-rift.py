#!/usr/bin/env python3
"""Build the T1 field-sketch Rift (recipe card T1, amended by critique-r0-t1.md).

Pure geometry on a 100x100 unit square, never traced. One ink, stroke only;
the chalk leader is the only accent. Built things ruled (frame, lanes, mid:
straight lines), water free (the river is the one curved line). No bows, no
hand jitter; the only seeded irregularity is +-0.6 units on each hatch's
inner end.

  python3 -I .planning/missions/M151/gallery/tools/build-t1-rift.py           # surfaces/art/t1-rift.svg
  python3 -I .planning/missions/M151/gallery/tools/build-t1-rift.py --inset   # surfaces/art/t1-inset.svg
"""
import math, random, pathlib, sys

ART = pathlib.Path(__file__).resolve().parent.parent / "surfaces" / "art"
rnd = random.Random(151)
f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")

def poly(pts):
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts)

# ---- River (T1-2): centreline point-symmetric about (50,50) ----------------
CUBICS = [((14, 14), (26, 30), (36, 40), (50, 50)),
          ((50, 50), (64, 60), (74, 70), (86, 86))]
RIVER_D = "M14,14 C26,30 36,40 50,50 C64,60 74,70 86,86"
BANK = 1.5

def bez(c, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = c
    u = 1 - t
    x = u**3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3
    y = u**3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3
    dx = 3 * u * u * (x1 - x0) + 6 * u * t * (x2 - x1) + 3 * t * t * (x3 - x2)
    dy = 3 * u * u * (y1 - y0) + 6 * u * t * (y2 - y1) + 3 * t * t * (y3 - y2)
    return x, y, dx, dy

CENTRE = []          # dense centreline samples, for distance tests
for c in CUBICS:
    for i in range(400):
        x, y, _, _ = bez(c, i / 400)
        CENTRE.append((x, y))
CENTRE.append((86, 86))

def river_dist(px, py):
    return min(math.hypot(px - x, py - y) for x, y in CENTRE)

def mid_dist(px, py):
    return abs(px + py - 100) / math.sqrt(2)

if "--inset" in sys.argv:
    # ---- T1-4: Match Day inset. No frame, no hatch, no labels. ------------
    BC, BR = (14, 86), 7                  # blue base circle
    SQ, SS = (82, 6), 12                  # red base square (centre 88,12)
    gap = 3
    yb = BC[1] - math.sqrt(BR**2 - (BC[0] - 10) ** 2) - gap      # top lane leaves the circle
    xb = BC[0] + math.sqrt(BR**2 - (90 - BC[1]) ** 2) + gap      # bot lane leaves the circle
    d = (BR + gap) / math.sqrt(2)
    def river_runs():
        # critique-r0b-t1 MD-2: centreline sampled 48 per cubic, samples within
        # 4 units of mid dropped -> an 8-unit bridge gap; mid stays continuous.
        runs, run = [], []
        for c in CUBICS:
            for i in range(49):
                if c is CUBICS[1] and i == 0: continue
                x, y, _, _ = bez(c, i / 48)
                if mid_dist(x, y) < 4:
                    if len(run) > 1: runs.append(poly(run))
                    run = []
                else:
                    run.append((x, y))
        if len(run) > 1: runs.append(poly(run))
        return runs
    ink = [
        poly([(10, yb), (10, 10), (SQ[0] - gap, 10)]),                       # top lane
        poly([(xb, 90), (90, 90), (90, SQ[1] + SS + gap)]),                  # bot lane
        poly([(BC[0] + d, BC[1] - d), (SQ[0] - gap / math.sqrt(2), SQ[1] + SS + gap / math.sqrt(2))]),  # mid
        *river_runs(),                                                       # river, broken at mid (MD-2)
        f"M{f(BC[0]-BR)},{f(BC[1])} a{BR},{BR} 0 1 0 {2*BR},0 a{BR},{BR} 0 1 0 {-2*BR},0",
        f"M{SQ[0]},{SQ[1]} H{SQ[0]+SS} V{SQ[1]+SS} H{SQ[0]} Z",
    ]
    out = ART / "t1-inset.svg"
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" class="rift rift-t1 rift-inset" aria-hidden="true" focusable="false">
<!-- GENERATED by tools/build-t1-rift.py --inset (critique-r0-t1 T1-4, critique-r0b-t1 MD-2). Do not edit by hand. -->
<g class="ink">{"".join(f'<path d="{p}"/>' for p in ink)}</g>
</svg>
'''
    out.write_text(svg)
    print(f"{out} {len(ink)} ink paths, {len(svg)} bytes")
    sys.exit(0)

BLUE = (12.0, 88.0)          # base circle r3 (blue side shape)
RED = (85.0, 9.0, 6.0)       # base square: top-left corner, side 6 (centre 88,12)
LABEL_CLEAR = [(20.5, 80.5, 46.0, 87.6)]          # "YOUR TEAM" clearing (x0,y0,x1,y1)
# Baron centre (31,27), Dragon centre (69,73) at 1280: mark (2.9 units) + word,
# each word on the side away from the river (Baron's to the right, Dragon's to the left).
MARK_CLEAR = [(28.5, 24.8, 41.0, 29.2), (58.5, 70.8, 71.5, 75.2)]

ink = []
# Frame (T1-1): four straight strokes stopping 1.5 short of each corner.
ink += [poly([(3.5, 2), (96.5, 2)]), poly([(98, 3.5), (98, 96.5)]),
        poly([(96.5, 98), (3.5, 98)]), poly([(2, 96.5), (2, 3.5)])]
# Lanes (T1-1): straight polylines, open ends at the bases.
ink.append("M10,84.5 L10,10 L83.5,10")
ink.append("M15.5,90 L90,90 L90,16.5")
ink.append("M15.2,84.8 L83.5,16.5")

# River banks (T1-2): 48 samples per cubic, offset +-1.5 along the normal,
# broken where a bank comes within 2 units of mid.
for s in (+1, -1):
    run = []
    for c in CUBICS:
        for i in range(49):
            if c is CUBICS[1] and i == 0: continue
            x, y, dx, dy = bez(c, i / 48)
            L = math.hypot(dx, dy)
            px, py = x - dy / L * BANK * s, y + dx / L * BANK * s
            if mid_dist(px, py) < 2:
                if len(run) > 1: ink.append(poly(run))
                run = []
            else:
                run.append((px, py))
    if len(run) > 1: ink.append(poly(run))

# Bases (side shapes, in ink).
ink.append(f"M{f(BLUE[0]-3)},{f(BLUE[1])} a3,3 0 1 0 6,0 a3,3 0 1 0 -6,0")
x, y, w = RED
ink.append(f"M{x},{y} H{x+w} V{y+w} H{x} Z")

def blocked(px, py):
    if math.hypot(px - BLUE[0], py - BLUE[1]) < 3 + 2.5: return True
    if RED[0] - 2.5 < px < RED[0] + RED[2] + 2.5 and RED[1] - 2.5 < py < RED[1] + RED[2] + 2.5: return True
    for x0, y0, x1, y1 in LABEL_CLEAR + MARK_CLEAR:
        if x0 < px < x1 and y0 < py < y1: return True
    return False

def stop(px, py):
    """Clip the hatch's inner end 2 units before the curved bank or mid."""
    return river_dist(px, py) < BANK + 2 or mid_dist(px, py) < 2

# Hatch (T1-3): perpendicular to its lane, 6-unit spacing, anchored 3 units
# off the lane, length 0.55 * (avail - 5), clipped short of bank and mid.
TRANSFORMS = {
    "left":   lambda x, y: (x, y),
    "right":  lambda x, y: (100 - x, 100 - y),     # point reflection through (50,50)
    "top":    lambda x, y: (y, x),                 # swap x and y
    "bottom": lambda x, y: (100 - y, 100 - x),     # swap of right
}
hatch = []
for name, T in TRANSFORMS.items():
    for yy in range(20, 81, 6):
        avail = 40 - abs(yy - 50)
        length = 0.55 * (avail - 5)
        if length < 3: continue
        a, b = T(13, yy), T(13 + length, yy)
        ux, uy = (b[0] - a[0]) / length, (b[1] - a[1]) / length
        # walk outward from the lane; stop at bank/mid; split at clearings
        runs, run, k = [], [], 0.0
        while k <= length + 1e-9:
            px, py = a[0] + ux * k, a[1] + uy * k
            if stop(px, py): break
            if blocked(px, py):
                if len(run) > 1: runs.append(run)
                run = []
            else:
                run.append((px, py))
            k += 0.1
        if len(run) > 1: runs.append(run)
        for i, r in enumerate(runs):
            p0, p1 = r[0], r[-1]
            last = i == len(runs) - 1
            jit = rnd.uniform(-0.6, 0.6) if last else 0.0
            # jitter only shortens when the end was clipped by bank/mid
            seg = math.hypot(p1[0] - p0[0], p1[1] - p0[1])
            if last and seg < length - 0.05: jit = -abs(jit)
            seg += jit
            if seg < 3: continue
            hatch.append(poly([p0, (p0[0] + ux * seg, p0[1] + uy * seg)]))

# Edge ticks: A..H along the top (8 columns), 1..5 down the left (5 rows), 1280 only.
ticks = []
for i in range(1, 8):
    xx = 2 + 96 * i / 8
    ticks.append(f"M{f(xx)},2 V0.4")
for i in range(1, 5):
    yy = 2 + 96 * i / 5
    ticks.append(f"M2,{f(yy)} H0.4")

# Chalk leader for the surveyed team label: from the blue base edge to the label.
leader = "M15.2,86.6 L22.3,84"

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" class="rift rift-t1" aria-hidden="true" focusable="false">
<!-- GENERATED by tools/build-t1-rift.py (recipe card T1 + critique-r0-t1). Do not edit by hand. -->
<g class="ticks">{"".join(f'<path d="{d}"/>' for d in ticks)}</g>
<g class="ink">{"".join(f'<path d="{d}"/>' for d in ink)}</g>
<g class="ink hatch">{"".join(f'<path d="{d}"/>' for d in hatch)}</g>
<g class="chalk" data-for="team-label"><path d="{leader}"/><path d="M15.2,86.6 h0"/></g>
</svg>
'''
out = ART / "t1-rift.svg"
out.write_text(svg)
print(f"{out} {len(ink)} ink paths, {len(hatch)} hatches, {len(svg)} bytes")
# Clearance check for the spot marks (centre to river centreline, minus the bank).
for nm, (mx, my) in (("Baron", (31, 27)), ("Dragon", (69, 73))):
    print(f"  {nm} centre ({mx},{my}): {river_dist(mx, my) - BANK:.2f} units clear of the near bank")

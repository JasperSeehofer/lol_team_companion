#!/usr/bin/env node
// extract-tokens.mjs: generate gallery/tokens.css from the app's input.css.
// No dependencies. Usage (from anywhere):
//   node .planning/missions/M151/gallery/tools/extract-tokens.mjs
// Every value is copied from input.css; nothing is invented. Tailwind
// wildcard resets (`--shadow-*: initial`) are skipped (not real properties).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const GALLERY = dirname(HERE);
const REPO = join(GALLERY, "..", "..", "..", "..");
const src = readFileSync(join(REPO, "input.css"), "utf8");
const FONT_PREFIX = relative(GALLERY, join(REPO, "public")).split("\\").join("/"); // ../../../../public

function block(name) {
  // body of the first `name {` block (no nested braces inside @theme / :root)
  const i = src.indexOf(name + " {");
  if (i < 0) throw new Error(`input.css: no "${name} {" block`);
  const start = src.indexOf("{", i) + 1;
  const end = src.indexOf("}", start);
  return src.slice(start, end);
}
function props(body) {
  const out = [];
  const clean = body.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const m of clean.matchAll(/(--[\w-]+(?:-\*)?)\s*:\s*([^;]+);/g)) {
    if (m[1].endsWith("-*")) continue; // Tailwind namespace reset
    // --animate-spin/pulse name Tailwind's built-in keyframes (spinner and
    // Skeleton only); the gallery has neither, and the lint bans the pulse.
    if (m[1].startsWith("--animate-")) continue;
    out.push([m[1], m[2].trim()]);
  }
  return out;
}

const theme = props(block("@theme"));
const root = props(block(":root"));
const rootExtra = /color-scheme:\s*([^;]+);/.exec(block(":root"))?.[1].trim();
const fontFaces = [...src.matchAll(/@font-face\s*\{[\s\S]*?\}/g)].map((m) =>
  m[0].replace(/url\("\/fonts\//g, `url("${FONT_PREFIX}/fonts/`),
);
// Utilities defined with @utility in input.css (eyebrow, note, figures).
const utilities = [...src.matchAll(/@utility\s+([\w-]+)\s*\{([\s\S]*?)\}/g)].map(
  ([, n, b]) => `.${n} {${b.replace(/\n {2}/g, "\n  ")}}`,
);
const themeNames = new Set(theme.map(([n]) => n));
const textSizes = theme
  .filter(([n]) => /^--text-[a-z]+$/.test(n))
  .map(([n]) => n.slice("--text-".length));
const typeHelpers = textSizes.map((s) => {
  const lh = themeNames.has(`--text-${s}--line-height`) ? `\n  line-height: var(--text-${s}--line-height);` : "";
  return `.text-${s} {\n  font-size: var(--text-${s});${lh}\n}`;
});

const decl = (list) => list.map(([n, v]) => `  ${n}: ${v};`).join("\n");
const css = `/* GENERATED by tools/extract-tokens.mjs from input.css. Do not edit by hand.
   Re-run: node .planning/missions/M151/gallery/tools/extract-tokens.mjs */

${fontFaces.join("\n")}

:root {
  color-scheme: ${rootExtra ?? "dark"};
  /* @theme (input.css) */
${decl(theme)}
  /* Tailwind v4 default spacing unit (input.css does not override it): 4px scale. */
  --spacing: 0.25rem;
  /* :root (input.css) */
${decl(root.filter(([n]) => n !== "color-scheme"))}
}

/* Base, mirroring input.css @layer base. */
html { background-color: var(--color-page); }
body {
  margin: 0;
  background-color: var(--color-page);
  color: var(--color-primary);
  font-family: var(--font-sans);
  font-size: var(--text-body);
  line-height: 1.5;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
  font-variant-numeric: tabular-nums;
}
h1, h2, h3, h4 { text-wrap: balance; }
:focus-visible { outline: 2px solid var(--focus-ring); outline-offset: 2px; }
kbd { font-family: var(--font-mono); }

/* Type helpers: Tailwind's text-* utilities from --text-* (size + leading). */
${typeHelpers.join("\n")}
.font-display { font-family: var(--font-display); }
.font-sans { font-family: var(--font-sans); }
.font-mono { font-family: var(--font-mono); }

/* Role utilities (input.css @utility). */
${utilities.join("\n")}

@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}
`;
writeFileSync(join(GALLERY, "tokens.css"), css);
console.log(`tokens.css: ${theme.length} @theme + ${root.length} :root properties, ${fontFaces.length} @font-face, ${typeHelpers.length + utilities.length} helpers`);

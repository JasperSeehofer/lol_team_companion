#!/usr/bin/env bash
# Remove background from a generated plane using fal.ai BiRefNet v2 (heavy model).
#
# EU policy exception (D-12): fal.ai is US-domiciled. Using it for BiRefNet is a
# documented exception because parallax plane images contain no personal data —
# GDPR exposure is zero for decorative architectural art. Exception logged in
# AI-IMAGES.md per the values-charter exception process.
#
# Sky planes skip this script — they are opaque and need no background removal.
# Apply only to: plane-mid, plane-near, overlay-{axis}-{1,2,3}.
#
# Usage:
#   ./scripts/remove-bg.sh <input.png> <output-transparent.png>
#
# Arguments:
#   <input.png>              Source PNG generated by gen-room-art.sh (from /tmp/...)
#   <output-transparent.png> Destination PNG with alpha channel (transparent background)
#
# Requires: curl, jq, FAL_KEY in environment
#
# Security (Pitfall 7 / T-30-08): The local PNG is uploaded to fal storage first
# so the BiRefNet input URL is an authenticated fal-controlled URL — never an
# expiring third-party host or a locally-served file. This prevents the attacker-
# controllable URL attack surface and avoids URL expiry races in long pipelines.
#
# NEVER echoes FAL_KEY into stdout/logs.
# Offline only — the server binary never calls this script.
set -euo pipefail

INPUT="${1:?Usage: remove-bg.sh <input.png> <output-transparent.png>}"
OUTPUT="${2:?Usage: remove-bg.sh <input.png> <output-transparent.png>}"

# Guard API key — never echoed
: "${FAL_KEY:?FAL_KEY must be set (export FAL_KEY=...); never hardcode}"

if [[ ! -f "$INPUT" ]]; then
    echo "Error: input file not found: ${INPUT}" >&2
    exit 1
fi

UPLOAD_RESP_TMP="$(mktemp /tmp/fal_upload_resp_XXXXXX.json)"
BIREFNET_RESP_TMP="$(mktemp /tmp/fal_birefnet_resp_XXXXXX.json)"

trap 'rm -f "$UPLOAD_RESP_TMP" "$BIREFNET_RESP_TMP"' EXIT

echo "Uploading source PNG to fal storage: ${INPUT}"

# --- 1. Upload local PNG to fal storage ---
# This avoids depending on an expiring or attacker-controllable public host
# (Pitfall 7 / T-30-08). The fal storage upload endpoint accepts a binary file
# and returns a stable fal-storage URL authenticated by FAL_KEY.
UPLOAD_RESP=$(curl -s -f -X POST "https://fal.run/storage/upload" \
    -H "Authorization: Key ${FAL_KEY}" \
    -H "Content-Type: image/png" \
    --data-binary "@${INPUT}")
echo "$UPLOAD_RESP" > "$UPLOAD_RESP_TMP"

FAL_STORAGE_URL=$(jq -r '.access_url // .url // empty' "$UPLOAD_RESP_TMP")
if [[ -z "$FAL_STORAGE_URL" ]]; then
    echo "Error: fal storage upload did not return a URL. Response:" >&2
    jq . "$UPLOAD_RESP_TMP" >&2
    exit 1
fi

echo "Uploaded to fal storage: ${FAL_STORAGE_URL}"

# --- 2. Run BiRefNet v2 with model=heavy ---
# model="heavy" gives best edge quality for painterly architectural elements.
echo "Running BiRefNet v2 (heavy) on fal storage URL..."
BIREFNET_RESP=$(curl -s -f -X POST "https://fal.run/fal-ai/birefnet/v2" \
    -H "Authorization: Key ${FAL_KEY}" \
    -H "Content-Type: application/json" \
    -d "{
        \"image_url\": \"${FAL_STORAGE_URL}\",
        \"model\": \"heavy\"
    }")
echo "$BIREFNET_RESP" > "$BIREFNET_RESP_TMP"

RESULT_URL=$(jq -r '.image.url // empty' "$BIREFNET_RESP_TMP")
if [[ -z "$RESULT_URL" ]]; then
    echo "Error: BiRefNet did not return .image.url. Response:" >&2
    jq . "$BIREFNET_RESP_TMP" >&2
    exit 1
fi

# --- 3. Download transparent PNG ---
mkdir -p "$(dirname "$OUTPUT")"
curl -L -s -f -o "$OUTPUT" "$RESULT_URL"

echo ""
echo "Done."
echo "  Input:  ${INPUT}"
echo "  Output: ${OUTPUT} (transparent PNG with alpha)"
echo ""
echo "Next step: encode-webp.sh ${OUTPUT} <dest>.webp"
echo ""
echo "Halo check reminder: before committing, open the resulting WebP against"
echo "background #070912 and verify no white/grey halo ring at edges (Pitfall 4 / SC3)."
